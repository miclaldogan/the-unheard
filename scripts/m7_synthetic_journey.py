# ruff: noqa: E501
"""M7: the full journey driven by the publishable synthetic set instead of ESC-50.

Same assertions as ``m55_real_journey.py``, but every clip is generated by ``m7_synthetic_sounds.py``, so the
audio carries this repository's own licence and may appear in a public demo. ESC-50 cannot.

Use only a fresh disposable backend; this creates recordings, annotations and compositions.

    python scripts/m7_synthetic_sounds.py generate
    UNHEARD_DATA_DIR=/tmp/unheard-m7 uv run --extra ml unheard serve --port 8011   # separate terminal
    UNHEARD_REVIEW_URL=http://127.0.0.1:8011 python scripts/m7_synthetic_journey.py

Every upload is stamped ``device_info={"source": "synthetic", "synthetic": true, ...}``, so a synthetic recording
stays distinguishable from a real field recording for the life of the database. Nothing here may be presented as
a field recording.
"""

import json
import os
import sys
import time
from pathlib import Path

import httpx

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from m7_synthetic_sounds import OUT as SET_DIR  # noqa: E402
from m7_synthetic_sounds import SPECIMENS  # noqa: E402

BASE = os.environ.get("UNHEARD_REVIEW_URL", "http://127.0.0.1:8011")
token = os.environ.get("UNHEARD_REVIEW_TOKEN")
c = httpx.Client(
    base_url=BASE,
    timeout=120,
    headers={"Authorization": f"Bearer {token}"} if token else {},
)
OUT = Path(os.environ.get("UNHEARD_REVIEW_DIR", str(ROOT / "docs" / "integration-review")))
OUT.mkdir(parents=True, exist_ok=True)

STAMP_BASE = {
    "source": "synthetic",
    "synthetic": True,
    "generator": "scripts/m7_synthetic_sounds.py",
    "note": "synthesised signal, not a field recording",
}


def get(p):
    r = c.get(p)
    r.raise_for_status()
    return r.json()


def post(p, **kw):
    r = c.post(p, **kw)
    r.raise_for_status()
    return r.json()


def wait(p, pred, limit=120):
    start = time.monotonic()
    j = None
    while time.monotonic() - start < limit:
        j = get(p)
        if pred(j):
            return j, (time.monotonic() - start) * 1000
        time.sleep(0.4)
    raise RuntimeError(f"timeout: {p} {j}")


def step(msg):
    print(f"  {msg}", flush=True)


# ---------------------------------------------------------------- preconditions

missing = [s.filename for s in SPECIMENS if not (SET_DIR / s.filename).exists()]
if missing:
    raise SystemExit(
        f"missing generated audio: {missing}\nrun: python scripts/m7_synthetic_sounds.py generate"
    )

state0 = get("/api/narrative/state")
assert state0["counts"]["taught"] == 0, "use a fresh disposable profile with no taught sounds"

start = time.monotonic()
model = post("/api/model/load")
assert model["status"] == "ready", model
print(
    f"model ready: {model['model_id']}@{model['revision'][:8]} on {model['device']} in {model['load_seconds']:.1f}s"
)

# ---------------------------------------------------------------- 1. upload and hear

print("\n1. upload + inference")
records = {}
for spec in SPECIMENS:
    path = SET_DIR / spec.filename
    stamp = {**STAMP_BASE, "group": spec.group, "role": spec.role, "params": spec.params}
    with path.open("rb") as fh:
        rec = post(
            "/api/recordings",
            files={"file": (spec.filename, fh, "audio/wav")},
            data={"device_info": json.dumps(stamp)},
        )
    rid = rec["recording_id"]
    detail, ready_ms = wait(f"/api/recordings/{rid}", lambda j: j["status"] == "ready")
    pred, infer_ms = wait(
        f"/api/recordings/{rid}/prediction",
        lambda j: j["state"] in ("awaiting_feedback", "inference_failed"),
    )
    assert pred["state"] == "awaiting_feedback", pred
    assert pred["model"]["id"] == "laion/clap-htsat-unfused", pred["model"]
    assert get(f"/api/recordings/{rid}/visual")
    records[spec.filename] = {
        "id": rid,
        "group": spec.group,
        "teach_as": spec.teach_as,
        "role": spec.role,
        "quality_flags": rec.get("quality", {}).get("flags", []),
        "ready_ms": round(ready_ms),
        "inference_ms": round(infer_ms),
        "top_base": [cand["name"] for cand in pred["base"]["candidates"][:3]],
    }
    step(
        f"{spec.filename:22s} {round(ready_ms):5d} ms ready  {round(infer_ms):5d} ms inferred  CLAP top: {records[spec.filename]['top_base'][0]}"
    )

# ---------------------------------------------------------------- 2. the memory proof

print("\n2. personalised memory: teach two, hold one out")
held_spec = next(s for s in SPECIMENS if s.teach_as is None)
taught_specs = [s for s in SPECIMENS if s.group == held_spec.group and s.teach_as]
label = taught_specs[0].teach_as
held_id = records[held_spec.filename]["id"]

before = get(f"/api/recordings/{held_id}/prediction")["fused"]["candidates"]
before_names = [x["name"] for x in before[:3]]
step(f"held-out top 3 before teaching: {before_names}")
assert label not in before_names, f"{label!r} already in the top 3 before teaching: {before_names}"

for s in taught_specs:
    post(f"/api/recordings/{records[s.filename]['id']}/annotations", json={"new_labels": [label]})
    step(f"taught {s.filename} as {label!r}")

after = get(f"/api/recordings/{held_id}/prediction")["fused"]["candidates"]
after_names = [x["name"] for x in after[:3]]
match = next((x for x in after if x["name"] == label), None)
assert match is not None, (
    f"{label!r} absent from the held-out prediction after teaching: {after_names}"
)
assert match["n_exemplars"] == 2, match
assert match["rank"] <= 3, match
step(f"held-out top 3 after teaching:  {after_names}")
step(
    f"{label!r} -> rank {match['rank']}, {match['n_exemplars']} exemplars, "
    f"memory similarity {match['memory_similarity']}, evidence {match['evidence']!r}"
)

# ---------------------------------------------------------------- 3. teach the rest

print("\n3. teach the held-out clip and the composition sources")
post(f"/api/recordings/{held_id}/annotations", json={"new_labels": [label]})
bells = [s for s in SPECIMENS if s.group != held_spec.group]
for s in bells:
    post(
        f"/api/recordings/{records[s.filename]['id']}/annotations",
        json={"new_labels": [s.teach_as]},
    )
    step(f"taught {s.filename} as {s.teach_as!r}")

# ---------------------------------------------------------------- 4. missions

print("\n4. missions")
missions = get("/api/narrative/missions")
activation = None
if missions.get("candidates"):
    activation = post(f"/api/narrative/missions/{missions['candidates'][0]['id']}/activate")
    step(f"activated: {missions['candidates'][0].get('title', missions['candidates'][0]['id'])}")
else:
    step("no mission candidates offered")

# ---------------------------------------------------------------- 5. composition

print("\n5. composed render from the three taught sources")
comp = post(
    "/api/compositions",
    json={
        "recording_ids": [records[s.filename]["id"] for s in bells],
        "mode": "composed",
        "seed": 55,
        "duration_s": 24,
    },
)
cid = comp.get("composition_id", comp.get("id"))
render, render_ms = wait(
    f"/api/compositions/{cid}", lambda j: j["status"] in ("ready", "failed"), 180
)
assert render["status"] == "ready", render
step(f"composition {cid} ready in {round(render_ms)} ms")

# ---------------------------------------------------------------- 6. narrative and ending

print("\n6. narrative + ending")
immediate = get("/api/narrative/current")["utterance"]
settled, narr_ms = wait(
    "/api/narrative/current",
    lambda j: j["utterance"]["generation"]["status"] != "pending",
    120,
)
state = get("/api/narrative/state")
assert state["ending_unlocked"], state
assert state["phase"] == "remembered", state
step(f"narrative settled in {round(narr_ms)} ms via {settled['utterance']['generation']['status']}")
step(f"phase {state['phase']}, ending unlocked")

commentary = get(f"/api/narrative/compositions/{cid}/commentary")
atlas = get("/api/atlas")
assert atlas.get("nodes"), atlas

# ---------------------------------------------------------------- report

report = {
    "audio_provenance": "deterministic synthetic signals from scripts/m7_synthetic_sounds.py; licensed with this repository; NOT field recordings",
    "esc50_used": False,
    "publishable": True,
    "device": model["device"],
    "model": {
        k: model[k]
        for k in ("model_id", "revision", "device", "embedding_dim", "preprocessing_version")
    },
    "records": records,
    "memory_proof": {
        "label": label,
        "held_out": held_spec.filename,
        "taught": [s.filename for s in taught_specs],
        "before_top3": before_names,
        "after_top3": after_names,
        "match": match,
    },
    "mission": activation,
    "composition": {"id": cid, "status": render["status"], "render_ms": round(render_ms)},
    "immediate_narrative": immediate,
    "settled_narrative": settled,
    "narrative_wait_ms": round(narr_ms),
    "state": state,
    "composition_commentary": commentary,
    "model_status": get("/api/narrative/model-status"),
    "atlas_nodes": len(atlas.get("nodes", [])),
    "total_s": round(time.monotonic() - start, 1),
}
dest = OUT / "synthetic-journey.json"
dest.write_text(json.dumps(report, indent=2) + "\n")

print(f"\nPASS  {report['total_s']} s   report -> {dest}")
print(
    json.dumps(
        {
            "ending": state["ending_unlocked"],
            "records": len(records),
            "memory": {
                "before": before_names,
                "after": after_names,
                "rank": match["rank"],
                "exemplars": match["n_exemplars"],
            },
            "render_ms": round(render_ms),
            "atlas_nodes": report["atlas_nodes"],
            "gemma": report["model_status"].get("stats"),
        },
        indent=2,
    )
)
